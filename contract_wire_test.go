// Cross-language wire contract — Go side.
//
// Asserts this SDK puts BYTE-IDENTICAL HTTP requests on the wire as the
// reference (TypeScript) SDK, for every op in the shared core surface. The
// expectation is not written here: it is read from
// tests/sdk/ts-request-fixtures.json, which tests/sdk/contract.test.ts
// regenerates from the reference SDK on every run. See that file for the design.
//
// WHY THIS LIVES IN sdk/go RATHER THAN tests/sdk: this rides the `go test ./...`
// job that already exists and already has the toolchain, so the gate cannot be
// dropped by "the contract job doesn't have Go installed". The four other
// bindings each do the same inside their own suite.
//
// WHAT IT CATCHES THAT A HAND-WRITTEN ASSERTION DOES NOT:
//
//  1. A create field this SDK never puts on the wire. Go's encoding/json silently
//     omits what isn't there, so `resolution`/`record`/`volumes` were missing from
//     CreateOptions for weeks with every test green — the fixture is MAXIMAL, so a
//     missing field is now a diff.
//  2. A core op this SDK doesn't implement at all. `coreOps` is iterated, not
//     cherry-picked: an op in the contract with no entry in the op table below is
//     a hard failure. That is how `pause`/`resume` are pinned — this SDK accepted
//     `lifecycle.onTimeout:"pause"` while offering NO WAY to resume the VM it had
//     just paused, and no per-field assertion would ever have noticed an ABSENCE.
//  3. A field removed from CreateOptions or createSandboxRequest: this file sets
//     every one of them, so deleting one fails the BUILD, before any assertion
//     runs. The compiler is Go's reflection here.
package solari

import (
	"context"
	"encoding/json"
	"io"
	"net/http"
	"net/http/httptest"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"sync"
	"testing"
)

// The canonical wire contract, regenerated by the TS reference suite.
//
// READ THROUGH THE testdata SYMLINK, NOT "../../tests/sdk/…" — THIS IS LOAD-BEARING.
// `go test` caches results, and it only tracks files the test opens INSIDE the
// module: a read of ../../tests/... is invisible to the cache, so changing the
// fixture alone left `go test ./...` reporting a stale "ok (cached)" — a gate that
// cannot fail is the bug this whole file exists to prevent. Measured both ways:
// via ../../ a tampered fixture still passed from cache; via testdata/ the same
// tamper re-runs and fails. CI's setup-go restores the build cache across runs
// keyed on go.sum, so this was reachable in CI, not just locally.
//
// (Go is the only one of the five with this hazard: cargo/ctest/pytest cache
// builds, never test results.)
const contractFixturePath = "testdata/wire-contract.json"

type wireRequest struct {
	Method string          `json:"method"`
	Path   string          `json:"path"`
	Body   json.RawMessage `json:"body,omitempty"`
}

type wireContract struct {
	SessionID string                 `json:"sessionId"`
	CoreOps   []string               `json:"coreOps"`
	Requests  map[string]wireRequest `json:"requests"`
}

type recordedReq struct {
	method string
	path   string
	body   []byte
}

func loadWireContract(t *testing.T) wireContract {
	t.Helper()
	raw, err := os.ReadFile(filepath.FromSlash(contractFixturePath))
	if err != nil {
		// HARD FAIL, never skip. The fixture is committed; its absence means the
		// checkout is broken or the reference suite never ran — either way this
		// test proves nothing, and "proves nothing" must not read as "passed".
		t.Fatalf("wire contract %s unreadable: %v", contractFixturePath, err)
	}
	var c wireContract
	if err := json.Unmarshal(raw, &c); err != nil {
		t.Fatalf("wire contract %s is not valid JSON: %v", contractFixturePath, err)
	}
	if len(c.CoreOps) == 0 || len(c.Requests) == 0 {
		t.Fatalf("wire contract %s carries no coreOps/requests — it is not a contract", contractFixturePath)
	}
	return c
}

// startContractGateway records every REST request and upgrades /control/* so a
// handle's post-resume reconnect can actually succeed (mirroring the TS fake
// gateway, which serves http + ws from one port).
func startContractGateway(t *testing.T) (*httptest.Server, *[]recordedReq) {
	t.Helper()
	var mu sync.Mutex
	rec := &[]recordedReq{}
	var srv *httptest.Server

	srv = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasPrefix(r.URL.Path, "/control/") {
			conn, err := testUpgrader.Upgrade(w, r, nil)
			if err != nil {
				return
			}
			// Hold the socket open; this suite asserts REST shapes, and the
			// channel only needs to be genuinely connected.
			go func() {
				defer conn.Close()
				for {
					if _, _, err := conn.ReadMessage(); err != nil {
						return
					}
				}
			}()
			return
		}

		raw, _ := io.ReadAll(r.Body)
		mu.Lock()
		// RequestURI(), not URL.Path: the raw, still-escaped path is the wire.
		// URL.Path would hand back a DECODED id and quietly launder exactly the
		// %3A-vs-: divergence this contract exists to pin.
		*rec = append(*rec, recordedReq{method: r.Method, path: r.URL.RequestURI(), body: raw})
		mu.Unlock()

		wsOrigin := "ws" + strings.TrimPrefix(srv.URL, "http")
		controlURL := wsOrigin + "/control/" + encodeURIComponent(canonicalSessionID)
		w.Header().Set("Content-Type", "application/json")

		switch {
		case r.Method == http.MethodPost && r.URL.Path == "/sandboxes":
			var body map[string]any
			_ = json.Unmarshal(raw, &body)
			kind, _ := body["kind"].(string)
			resp := map[string]any{
				"sandboxId":  canonicalSessionID,
				"kind":       kind,
				"controlUrl": controlURL,
				"expiresAt":  "2026-01-01T00:00:00Z",
			}
			if kind == "desktop" {
				resp["streamUrl"] = wsOrigin + "/stream/" + encodeURIComponent(canonicalSessionID)
			}
			w.WriteHeader(201)
			_ = json.NewEncoder(w).Encode(resp)
		case r.Method == http.MethodPost && strings.HasSuffix(r.URL.Path, "/pause"):
			_ = json.NewEncoder(w).Encode(map[string]any{"state": "paused"})
		case r.Method == http.MethodPost && strings.HasSuffix(r.URL.Path, "/resume"):
			// The session comes back on a FRESH slot, so the gateway hands back
			// the control URL to re-attach to.
			_ = json.NewEncoder(w).Encode(map[string]any{"state": "running", "controlUrl": controlURL})
		case r.Method == http.MethodPost && strings.HasSuffix(r.URL.Path, "/start"):
			_ = json.NewEncoder(w).Encode(map[string]any{"state": "running", "controlUrl": controlURL})
		case r.Method == http.MethodGet && strings.HasPrefix(r.URL.Path, "/sandboxes/"):
			_ = json.NewEncoder(w).Encode(map[string]any{
				"sandboxId": canonicalSessionID,
				"kind":      "sandbox",
				"state":     "running",
				"expiresAt": "2026-01-01T00:00:00Z",
				"cpu":       2,
				"memMb":     2048,
			})
		case r.Method == http.MethodDelete:
			_ = json.NewEncoder(w).Encode(map[string]any{"ok": true})
		default:
			w.WriteHeader(404)
			_ = json.NewEncoder(w).Encode(map[string]any{"error": "not_found"})
		}
	}))
	t.Cleanup(srv.Close)
	return srv, rec
}

// canonicalSessionID mirrors the fixture's sessionId; asserted equal below so the
// two cannot drift apart silently.
const canonicalSessionID = "pool-a:vm-7:org-42.sig"

// jsonEq compares two JSON payloads structurally (key order is not the wire).
func jsonEq(t *testing.T, got, want []byte) bool {
	t.Helper()
	var g, w any
	if len(got) > 0 {
		if err := json.Unmarshal(got, &g); err != nil {
			t.Errorf("recorded body is not JSON: %v", err)
			return false
		}
	}
	if len(want) > 0 {
		if err := json.Unmarshal(want, &w); err != nil {
			t.Errorf("fixture body is not JSON: %v", err)
			return false
		}
	}
	return reflect.DeepEqual(g, w)
}

// TestWireContractMatchesReferenceSDK is the gate: every op the contract names,
// driven through the REAL client, must hit the wire exactly as the reference does.
func TestWireContractMatchesReferenceSDK(t *testing.T) {
	contract := loadWireContract(t)
	if contract.SessionID != canonicalSessionID {
		t.Fatalf("fixture sessionId %q != this suite's %q — the contract moved under us",
			contract.SessionID, canonicalSessionID)
	}

	srv, rec := startContractGateway(t)
	zero := 0
	c, err := NewClient(ClientOptions{APIKey: "key-test", BaseURL: srv.URL, RetryDelayMs: &zero})
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()

	// The maximal create DTO, field-for-field the TS reference's. EVERY field of
	// CreateOptions is set on purpose: deleting one from the struct breaks this
	// build, so the DTO cannot shrink without somebody noticing.
	autoResume := true
	recordOn := true
	common := CreateOptions{
		CPU:          2,
		MemMb:        2048,
		DiskGb:       10,
		Envs:         map[string]string{"FOO": "bar"},
		Metadata:     map[string]string{"proj": "alpha"},
		TimeoutMs:    600_000,
		TtlSeconds:   3600,
		FromSnapshot: "snap_seed",
		// Isolation is set per-op below (dedicated for the sandbox, hardened
		// for the desktop, matching the TS reference exactly) rather than here
		// -- "shared" is refused for desktops, so the two calls cannot share
		// one isolation value.
		Lifecycle: &SandboxLifecycle{
			OnTimeout:              "pause",
			AutoResume:             &autoResume,
			ParkAfterMs:            30_000,
			ParkMaxMs:              20_000,
			HibernateAfterParkedMs: 90_000,
			CheckpointEveryMs:      300_000,
		},
		Volumes: []VolumeAttachment{{VolumeID: "vol_data", Path: "/data"}},
	}

	var sb *Sandbox

	// THE OP TABLE. Every op the contract names must appear here, bound to the
	// real SDK call that performs it.
	ops := map[string]func() error{
		"createSandbox": func() error {
			o := common
			o.Template = "base"
			o.Isolation = IsolationDedicated
			var err error
			sb, err = c.Create(ctx, o)
			return err
		},
		"createDesktop": func() error {
			o := common
			o.Template = "default"
			o.Kind = KindDesktop
			o.Resolution = "1280x720"
			o.Record = &recordOn
			o.Isolation = IsolationHardened
			d, err := c.Create(ctx, o)
			if err == nil {
				d.Close()
			}
			return err
		},
		"get": func() error {
			_, err := c.Get(ctx, canonicalSessionID)
			return err
		},
		"pause": func() error {
			if err := sb.Pause(ctx); err != nil {
				return err
			}
			// Asserted here, not at the end: Kill closes the channel too, so a
			// check after the loop would pass whether or not Pause touched it.
			if sb.Connected() {
				t.Error("pause: control channel still open")
			}
			return nil
		},
		"resume": func() error {
			if err := sb.Resume(ctx); err != nil {
				return err
			}
			if !sb.Connected() {
				t.Error("resume: control channel not re-opened on the fresh slot")
			}
			return nil
		},
		"start": func() error {
			if err := sb.Start(ctx); err != nil {
				return err
			}
			if !sb.Connected() {
				t.Error("start: control channel not re-opened on the fresh control URL")
			}
			return nil
		},
		"kill": func() error { return sb.Kill(ctx) },
	}

	// A CHECKLIST THAT FAILS CLOSED. The contract is iterated, so an op this SDK
	// does not implement is a failure here rather than a silent omission.
	var have []string
	for name := range ops {
		have = append(have, name)
	}
	want := append([]string(nil), contract.CoreOps...)
	sortStrings(have)
	sortStrings(want)
	if !reflect.DeepEqual(have, want) {
		t.Fatalf("op table does not match the contract's coreOps:\n  this SDK: %v\n  contract: %v\n"+
			"An op in the contract with no entry here is a surface this binding is missing.", have, want)
	}

	for _, name := range contract.CoreOps {
		op, ok := ops[name]
		if !ok {
			t.Errorf("%s: NOT IMPLEMENTED in the Go SDK op table", name)
			continue
		}
		before := len(*rec)
		if err := op(); err != nil {
			t.Errorf("%s: %v", name, err)
			continue
		}
		made := (*rec)[before:]
		// An op that emitted nothing must never compare equal to anything.
		if len(made) != 1 {
			t.Errorf("%s: emitted %d HTTP requests, want exactly 1", name, len(made))
			continue
		}
		got, exp := made[0], contract.Requests[name]
		if got.method != exp.Method || got.path != exp.Path {
			t.Errorf("%s: wire mismatch\n  got  %s %s\n  want %s %s",
				name, got.method, got.path, exp.Method, exp.Path)
		}
		if !jsonEq(t, got.body, exp.Body) {
			t.Errorf("%s: body mismatch\n  got  %s\n  want %s", name, got.body, exp.Body)
		}
	}
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

// TestEncodeURIComponentMatchesJS pins the escaping the contract's paths depend
// on. url.PathEscape is NOT a substitute: it leaves ':' alone (RFC 3986 allows it
// in a path), and session ids are `<poolId>:<vmId>:<orgId>.<sig>` — all colons.
func TestEncodeURIComponentMatchesJS(t *testing.T) {
	cases := map[string]string{
		"pool-a:vm-7:org-42.sig": "pool-a%3Avm-7%3Aorg-42.sig",
		"p@ss word":              "p%40ss%20word",
		"a-_.!~*'()":             "a-_.!~*'()", // unreserved, passes through
		"a/b?c#d":                "a%2Fb%3Fc%23d",
	}
	for in, want := range cases {
		if got := encodeURIComponent(in); got != want {
			t.Errorf("encodeURIComponent(%q) = %q, want %q", in, got, want)
		}
	}
}
